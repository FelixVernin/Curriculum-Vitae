import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const sourcePath = join(root, 'profil_felix.md')
const outputPath = join(root, 'src', 'profile.ts')
const profile = await readFile(sourcePath, 'utf8')

await writeFile(
  outputPath,
  `// Generated by scripts/generate-profile.mjs. Do not edit manually.\nexport const PROFILE = ${JSON.stringify(profile)} as const\n`,
  'utf8'
)
